export const COMPUTER_METHOD_SOURCE: MethodSource = {
  params(m) {
    const entry = COMPUTER_METHODS[m as ComputerMethod]
    if (!entry) throw new Error(`${m} is not in COMPUTER_METHODS`)
    return entry.params
  }
}

